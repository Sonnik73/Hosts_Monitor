package com.servermon.monitor.util

import android.content.Context
import android.util.Base64
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.put
import java.security.SecureRandom

data class PeerSpec(val name: String, val host: String, val port: Int)

data class AgentSpec(
    val listenPort: Int,
    val token: String,
    val mounts: List<String>,
    val services: List<String>,
    val peers: List<PeerSpec>,
)

/**
 * Builds a self-contained installer script: the agent (embedded base64) +
 * personalized config.json + systemd unit, all in one bash file.
 * Upload it to the server (Termius snippet/SFTP) and run: sudo bash servermon-install.sh
 */
object InstallerGenerator {

    fun randomToken(): String {
        val bytes = ByteArray(24)
        SecureRandom().nextBytes(bytes)
        return bytes.joinToString("") { "%02x".format(it) }
    }

    fun buildConfigJson(spec: AgentSpec): JsonObject = buildJsonObject {
        put("listen_host", "0.0.0.0")
        put("listen_port", spec.listenPort)
        put("token", spec.token)
        put("mounts", JsonArray(spec.mounts.map { kotlinx.serialization.json.JsonPrimitive(it) }))
        put("services", JsonArray(spec.services.map { kotlinx.serialization.json.JsonPrimitive(it) }))
        put(
            "peers",
            JsonArray(spec.peers.map { p ->
                buildJsonObject {
                    put("name", p.name)
                    put("host", p.host)
                    put("port", p.port)
                }
            })
        )
        put("top_processes_limit", 5)
    }

    fun buildScript(context: Context, spec: AgentSpec): String {
        val agentSrc = context.assets.open("agent.py").bufferedReader().readText()
        val b64 = Base64.encodeToString(agentSrc.toByteArray(Charsets.UTF_8), Base64.NO_WRAP)
        val cfg = buildConfigJson(spec).toString()

        return """
            #!/usr/bin/env bash
            # ServerMon agent installer — generated by Hosts Monitor app
            # Usage: upload this file to the server, then:  sudo bash servermon-install.sh
            set -euo pipefail

            if [ "${'$'}(id -u)" -ne 0 ]; then
              echo "Запустите от root: sudo bash ${'$'}0" >&2
              exit 1
            fi

            command -v python3 >/dev/null || { echo "Нужен python3 (apt install python3)" >&2; exit 1; }

            echo "[1/4] Устанавливаю agent.py..."
            base64 -d > /usr/local/bin/servermon-agent.py <<'AGENT_B64'
            $b64
            AGENT_B64
            chmod 755 /usr/local/bin/servermon-agent.py

            echo "[2/4] Пишу /etc/servermon/config.json..."
            mkdir -p /etc/servermon
            cat > /etc/servermon/config.json <<'CONFIG_JSON'
            $cfg
            CONFIG_JSON
            chmod 600 /etc/servermon/config.json

            echo "[3/4] Ставлю systemd-юнит..."
            cat > /etc/systemd/system/servermon-agent.service <<'UNIT'
            [Unit]
            Description=ServerMon metrics agent
            After=network-online.target
            Wants=network-online.target

            [Service]
            Type=simple
            ExecStart=/usr/bin/python3 /usr/local/bin/servermon-agent.py
            Restart=always
            RestartSec=10
            NoNewPrivileges=true
            ProtectSystem=strict
            ProtectHome=true
            ReadOnlyPaths=/etc/servermon
            PrivateTmp=true

            [Install]
            WantedBy=multi-user.target
            UNIT

            echo "[4/4] Запускаю сервис..."
            systemctl daemon-reload
            systemctl enable servermon-agent.service
            systemctl restart servermon-agent.service

            echo
            echo "=== Готово! Проверка: ==="
            echo "  systemctl status servermon-agent"
            echo "  curl -s -H 'X-Auth-Token: ${spec.token}' http://127.0.0.1:${spec.listenPort}/health"
            echo
            echo "Откройте порт ${spec.listenPort} в файрволе только для доверенных источников (VPN)."
        """.trimIndent()
    }
}
